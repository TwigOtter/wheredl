// Index 0's local calendar date, in America/Chicago (Kansas City).
const SEQUENCE_EPOCH_DATE = "2026-08-18";
const DAY_MS = 24 * 60 * 60 * 1000;

/** Today's index into DAILY_CITY_OBJECT_IDS, advancing once per calendar day at midnight America/Chicago. */
export function todaysDayIndex(): number {
  const todayChicago = new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/Chicago",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date());

  const daysSinceEpoch = Math.round(
    (Date.parse(`${todayChicago}T00:00:00Z`) -
      Date.parse(`${SEQUENCE_EPOCH_DATE}T00:00:00Z`)) /
      DAY_MS,
  );

  const length = DAILY_CITY_OBJECT_IDS.length;
  return ((daysSinceEpoch % length) + length) % length;
}

/** The OBJECTID for a given day index, wrapping once the list is exhausted. */
export function cityObjectIdForDay(dayIndex: number): number {
  const length = DAILY_CITY_OBJECT_IDS.length;
  const normalized = ((dayIndex % length) + length) % length;
  return DAILY_CITY_OBJECT_IDS[normalized];
}
